"""Step 08c — stage 3: SwinIR fine-tuning (L1 loss, no GAN, official DF2K classical pretrained weights).

  data   results/sr08/data/hr/train (TCGA Q70, 0.5 µm, 256 px). Low-resolution inputs are generated at each draw with the sr02 v2 degradation
         (new degradation parameters every time, acting as augmentation), then random rotation / flip and aligned crops of LR 64 px / HR 64·s px.
  val    first 200 val tiles with fixed low-res inputs (pre-generated by sr08b); every 1000 iterations L1 / PSNR (Y channel) of SR and bicubic;
         model selection uses only the TCGA validation set — HEST / Xenium are not used.
  saves   results/sr08/models/x<s>/{last.pth, best.pth, log.csv, val_examples.png}
  low load: nice 10, 4 torch threads, 2 data workers, one model at a time on MPS.
Usage: nice -n 10 python scripts/sr08c_train_swinir.py --scale 2
"""
from __future__ import annotations

import argparse
import math
import os
import sys
import time
from pathlib import Path

os.environ.setdefault("OMP_NUM_THREADS", "4")
os.environ.setdefault("PYTORCH_ENABLE_MPS_FALLBACK", "1")

import cv2  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import torch  # noqa: E402
import torch.nn.functional as F  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "scripts"), "/Volumes/INTENSO/models/SwinIR"]
from network_swinir import SwinIR  # noqa: E402
from sr02_degrade_benchmark import degrade_real2  # noqa: E402

DATA = ROOT / "results" / "sr08" / "data"
WEIGHTS = Path("/Volumes/INTENSO/models/SwinIR")
GT_PX, LR_PATCH = 256, 64
N_VAL = 200


def build(scale: int, pretrained: bool = True) -> SwinIR:
    m = SwinIR(upscale=scale, in_chans=3, img_size=64, window_size=8, img_range=1., depths=[6] * 6, embed_dim=180,
               num_heads=[6] * 6, mlp_ratio=2, upsampler="pixelshuffle", resi_connection="1conv")
    if pretrained:
        sd = torch.load(WEIGHTS / f"001_classicalSR_DF2K_s64w8_SwinIR-M_x{scale}.pth", map_location="cpu")
        m.load_state_dict(sd.get("params", sd), strict=True)
    return m


class TrainSet(torch.utils.data.Dataset):
    def __init__(self, scale: int, seed: int):
        self.files = sorted((DATA / "hr" / "train").glob("*.png"))
        self.scale, self.seed = scale, seed

    def __len__(self):
        return len(self.files)

    def __getitem__(self, i):
        info = torch.utils.data.get_worker_info()
        rng = np.random.default_rng([self.seed, i, int(time.time_ns() % 2 ** 31), info.id if info else 0])
        hr = cv2.imread(str(self.files[i]))[..., ::-1]
        k = int(rng.integers(4))
        hr = np.rot90(hr, k)
        if rng.random() < 0.5:
            hr = hr[:, ::-1]
        hr = np.ascontiguousarray(hr)
        lr, _ = degrade_real2(hr, GT_PX // self.scale, rng)
        n = lr.shape[0]
        y, x = rng.integers(0, n - LR_PATCH + 1, 2)
        s = self.scale
        lr = lr[y:y + LR_PATCH, x:x + LR_PATCH]
        hr = hr[y * s:(y + LR_PATCH) * s, x * s:(x + LR_PATCH) * s]
        t = lambda a: torch.from_numpy(a.transpose(2, 0, 1).astype(np.float32) / 255.0)
        return t(lr), t(hr)


def to_y(x: torch.Tensor) -> torch.Tensor:
    return (65.481 * x[:, 0] + 128.553 * x[:, 1] + 24.966 * x[:, 2] + 16.0) / 255.0


def psnr_y(a, b) -> float:
    mse = F.mse_loss(to_y(a), to_y(b)).item()
    return 10 * math.log10(1.0 / max(mse, 1e-12))


def load_val(scale: int):
    ids = sorted(p.stem for p in (DATA / f"val_lr_{0.5 * scale:.1f}").glob("*.png"))[:N_VAL]
    rd = lambda p: torch.from_numpy(cv2.imread(str(p))[..., ::-1].transpose(2, 0, 1).copy()).float() / 255.0
    lr = torch.stack([rd(DATA / f"val_lr_{0.5 * scale:.1f}" / f"{i}.png") for i in ids])
    hr = torch.stack([rd(DATA / "hr" / "val" / f"{i}.png") for i in ids])
    return lr, hr


@torch.no_grad()
def validate(model, lr, hr, device, bs=8):
    model.eval()
    l1s, ps, l1b, pb = [], [], [], []
    for i in range(0, len(lr), bs):
        x, y = lr[i:i + bs].to(device), hr[i:i + bs].to(device)
        sr = model(x).clamp(0, 1)
        bc = F.interpolate(x, size=y.shape[-2:], mode="bicubic", align_corners=False).clamp(0, 1)
        l1s.append(F.l1_loss(sr, y).item()); ps.append(psnr_y(sr, y))
        l1b.append(F.l1_loss(bc, y).item()); pb.append(psnr_y(bc, y))
    model.train()
    return np.mean(l1s), np.mean(ps), np.mean(l1b), np.mean(pb)


def save_examples(model, lr, hr, device, dst: Path):
    model.eval()
    with torch.no_grad():
        x = lr[:4].to(device)
        sr = model(x).clamp(0, 1).cpu()
        bc = F.interpolate(x, size=hr.shape[-2:], mode="bicubic", align_corners=False).clamp(0, 1).cpu()
    model.train()
    up = F.interpolate(lr[:4], size=hr.shape[-2:], mode="nearest")
    rows = [torch.cat(list(t), dim=2) for t in (up, bc, sr, hr[:4])]          # rows: low-res (nearest) / bicubic / SR / high-res
    grid = (torch.cat(rows, dim=1).numpy().transpose(1, 2, 0) * 255).astype(np.uint8)
    cv2.imwrite(str(dst), grid[..., ::-1])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scale", type=int, choices=[2, 4, 8], required=True)
    ap.add_argument("--iters", type=int, default=15000)
    ap.add_argument("--batch", type=int, default=8)
    ap.add_argument("--lr", type=float, default=1e-4)
    ap.add_argument("--val-every", type=int, default=1000)
    ap.add_argument("--seed", type=int, default=2026)
    args = ap.parse_args()
    torch.set_num_threads(4)
    torch.manual_seed(args.seed)
    device = "mps"
    out = ROOT / "results" / "sr08" / "models" / f"x{args.scale}"
    out.mkdir(parents=True, exist_ok=True)

    model = build(args.scale).to(device).train()
    opt = torch.optim.Adam(model.parameters(), lr=args.lr, betas=(0.9, 0.99))
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=args.iters, eta_min=1e-6)
    dl = torch.utils.data.DataLoader(TrainSet(args.scale, args.seed), batch_size=args.batch, shuffle=True,
                                     num_workers=2, drop_last=True, persistent_workers=True)
    vlr, vhr = load_val(args.scale)

    l1, p, l1b, pb = validate(model, vlr, vhr, device)
    log = [{"iter": 0, "train_l1": np.nan, "val_l1": l1, "val_psnr": p, "bicubic_l1": l1b, "bicubic_psnr": pb}]
    print(f"[0] pretrained weights:val L1 {l1:.4f} PSNR {p:.2f} | bicubic L1 {l1b:.4f} PSNR {pb:.2f}", flush=True)
    save_examples(model, vlr, vhr, device, out / "val_examples_iter0.png")
    best = l1
    torch.save(model.state_dict(), out / "best.pth")
    it, run, t0 = 0, [], time.time()
    while it < args.iters:
        for x, y in dl:
            x, y = x.to(device), y.to(device)
            loss = F.l1_loss(model(x), y)
            opt.zero_grad(set_to_none=True)
            loss.backward()
            opt.step()
            sched.step()
            it += 1
            run.append(loss.item())
            if it == 50:
                eta = (time.time() - t0) / 50 * args.iters / 3600
                print(f"  50 iterations took {time.time() - t0:.0f} s, estimated total {eta:.1f} h", flush=True)
            if it % args.val_every == 0 or it == args.iters:
                l1, p, l1b, pb = validate(model, vlr, vhr, device)
                log.append({"iter": it, "train_l1": float(np.mean(run)), "val_l1": l1, "val_psnr": p,
                            "bicubic_l1": l1b, "bicubic_psnr": pb})
                run = []
                pd.DataFrame(log).to_csv(out / "log.csv", index=False)
                torch.save(model.state_dict(), out / "last.pth")
                if l1 < best:
                    best = l1
                    torch.save(model.state_dict(), out / "best.pth")
                print(f"[{it}] train L1 {log[-1]['train_l1']:.4f} | val L1 {l1:.4f} PSNR {p:.2f} "
                      f"(bicubic {pb:.2f})| lr {sched.get_last_lr()[0]:.2e} | {(time.time() - t0) / 60:.0f} min", flush=True)
            if it >= args.iters:
                break
    save_examples(model, vlr, vhr, device, out / "val_examples_final.png")
    print("done:", out)


if __name__ == "__main__":
    main()
